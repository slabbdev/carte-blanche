/**
 * apimatic-mcp-gen.mjs — PROTOTYPE for APIMatic (the sponsor-gift pitch).
 *
 * Reads an OpenAPI 3 spec and emits an MCP server skeleton: one tool per
 * operation, params from the schema, auth from the spec's security schemes.
 * The pitch to APIMatic: their pipeline already produces SDKs + portals from
 * a spec — it could produce THIS next to them, so every customer's API is
 * not just documented for agents but CALLABLE by agents.
 *
 * Usage:  node scripts/apimatic-mcp-gen.mjs docs/openapi.json out/mcp-server.ts
 * The output is a starting point: wire your transport (stdio/HTTP), fill the
 * request layer, review tool descriptions.
 *
 * Demo scope: GET operations only, flat query/path params, bearer security.
 * Kept dependency-free on purpose — paste into any MCP SDK quickstart.
 */
import { readFileSync, writeFileSync } from "node:fs";

const [, , specPath = "docs/openapi.json", outPath = "out/mcp-server.ts"] = process.argv;
const spec = JSON.parse(readFileSync(specPath, "utf8"));

const serverName = (spec.info?.title ?? "api").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
const ops = [];
for (const [path, pathItem] of Object.entries(spec.paths ?? {})) {
  for (const [method, op] of Object.entries(pathItem)) {
    if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
    const params = [
      ...(pathItem.parameters ?? []),
      ...(op.parameters ?? []),
    ].map((p) => ({ name: p.name, in: p.in, required: Boolean(p.required), type: p.schema?.type ?? "string", desc: p.description ?? "" }));
    const bodySchema = op.requestBody?.content?.["application/json"]?.schema;
    ops.push({
      name: (op.operationId ?? `${method}${path}`).replace(/[^a-zA-Z0-9_]/g, "_"),
      method: method.toUpperCase(),
      path,
      summary: op.summary ?? op.description ?? `${method.toUpperCase()} ${path}`,
      params,
      hasBody: Boolean(bodySchema),
      tags: op.tags ?? [],
    });
  }
}

const authHeader = (spec.components?.securitySchemes && Object.keys(spec.components.securitySchemes).length)
  ? "Authorization: `Bearer ${process.env.API_TOKEN}`"
  : "/* no security scheme in spec */ undefined";

const tool = (op) => {
  const args = op.params.map((p) => `    ${p.name}: z.${p.type === "integer" || p.type === "number" ? "number()" : "string()"}${p.required ? "" : ".optional()"},`).join("\n");
  const body = op.hasBody ? `    body: z.record(z.unknown()).optional(),` : "";
  const allArgs = [args, body].filter(Boolean).join("\n");
  return `server.tool(
  "${op.name}",
  ${JSON.stringify(op.summary)},
  {
${allArgs}
  },
  async (a) => {
    let path = "${op.path}";
    for (const [k, v] of Object.entries(a)) path = path.replace("{" + k + "}", encodeURIComponent(String(v)));
    const qs = new URLSearchParams(Object.entries(a).filter(([k, v]) => v !== undefined && !path.includes("{" + k + "}")).map(([k, v]) => [k, String(v)]));
    const res = await fetch(BASE + path + (qs.toString() ? "?" + qs : ""), {
      method: "${op.method}",
      headers: { "Content-Type": "application/json", ${authHeader} },
      ${op.hasBody ? "body: a.body ? JSON.stringify(a.body) : undefined," : ""}
    });
    return { content: [{ type: "text", text: JSON.stringify(await res.json().catch(() => ({})), null, 2) }] };
  },
);`;
};

const file = `// GENERATED by apimatic-mcp-gen.mjs from ${spec.info?.title ?? "spec"} v${spec.info?.version ?? "?"}
// Wire into @modelcontextprotocol/sdk (StdioServerTransport) and review tools.
import { z } from "zod";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";

const BASE = process.env.API_BASE ?? ${JSON.stringify((spec.servers ?? [{ url: "https://api.example.com" }])[0].url)};
const AUTH = ${authHeader === "/* no security scheme in spec */ undefined" ? "undefined" : authHeader};

export function registerTools(server: McpServer) {
${ops.map(tool).join("\n\n")}
}
`;

writeFileSync(outPath, file);
console.log(`${ops.length} tools emitted for ${ops.filter((o) => o.method === "GET").length} GET ops -> ${outPath}`);
console.log("next: wire McpServer transport, review tool descriptions, ship.");
